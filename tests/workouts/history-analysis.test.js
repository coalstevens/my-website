const assert=require('node:assert/strict');
const fs=require('node:fs');
const A=require('../../workouts/js/history-analysis.js');
const C=require('../../tools/workouts/archive-cleanup.js');
assert.deepEqual(A.result('8'),{kind:'reps',reps:8});
assert.deepEqual(A.result('10s'),{kind:'duration',seconds:10});
assert.deepEqual(A.result('6 × 7s'),{kind:'repeaters',reps:6,seconds:7});
for(const value of ['8/6','max','5 + 3','', '8 reps maybe']) assert.equal(A.result(value),null);
assert.equal(A.load('175 - 35s/25s/5s'),175);
assert.equal(A.load('20 lb'),20);
assert.equal(A.load('bodyweight'),null);
assert.equal(A.load('20 / 25'),null);
assert.equal(A.name('  Pullups -- ss '),'pullups');
const workouts=[{id:'one',date:'2026-01-01',rows:[['hang','','6 × 7s','4 × 8s'],['press','25','8','7'],['','30','6',''],['note','','unclear','']]},{id:'two',date:'2026-03-01',rows:[['press','35','5','']]}];
const {sets,unparsed}=A.records(workouts,{'one:1:1':'27.5','one:2:2':'7'});
assert.equal(unparsed,1);assert.equal(sets.length,4);
assert.equal(sets[1].weight,27.5);assert.equal(sets[2].results[0].reps,7);
const summary=A.summarize(sets);assert.equal(summary[0].exercise,'press');assert.equal(summary[0].sets,3);assert.equal(summary[0].sessions,2);assert.equal(summary[0].load,35);
assert.equal(summary.find(row=>row.exercise==='hang').reps,null);
assert.equal(summary.find(row=>row.exercise==='hang').repeaters,42);
const calendar=A.calendar([{date:'2024-02-29'},{date:'2024-02-29'},{date:'2024-03-01'}],'2024-02-01','2024-02-29');
assert.equal(calendar.length,1);
assert.equal(calendar[0].days.length,366);
assert.equal(calendar[0].days.find(day=>day.date==='2024-02-29').count,2);
assert.equal(calendar[0].days.find(day=>day.date==='2024-02-29').weekday,4);
assert.equal(calendar[0].days.find(day=>day.date==='2024-03-01').inRange,false);
assert.equal(calendar[0].days.find(day=>day.date==='2024-03-01').count,0);
assert.equal(A.calendar([],'2025-01-01','2025-12-31')[0].days.length,365);
assert.equal(A.calendar([],'2024-12-31','2025-01-01').length,2);
assert.deepEqual(A.calendar([],'2025-12-31','2025-01-01'),[]);
for (const value of ['rows','low row','Bent over row']) assert.equal(C.title(value),'low row');
assert.equal(C.title('Negatives'),'one arm negatives');
assert.equal(C.title('spotter arm bat hang'),'bat hang');
const cleaned=A.records([C.cleanSession({id:'cleanup',date:'2026-01-01',rows:[
  ['Pullups','bw 180','5',''],['good form only baby','25','6',''],['','50','4',''],
  ['explosive pullups -- ss','','3',''],['rows','30','8',''],
  ['on machine','40','6',''],['Density','bw','30',''],['','5','25','']
]})]).sets;
assert.equal(cleaned.length,6);
assert.deepEqual(cleaned.slice(0,3).map(set=>set.exercise),['weighted pullups','weighted pullups','weighted pullups']);
assert.equal(cleaned[0].weight,null);
assert.equal(cleaned[3].exercise,'explosive pullups');
assert.deepEqual(cleaned.slice(4).map(set=>set.exercise),['low row','low row']);
assert.equal(A.records([{id:'bw',date:'2026-01-01',rows:[['pullups','bw 180','8','']]}]).sets[0].exercise,'pullups');
const recentFixture=[...sets,{session:'latest',date:'2026-05-01',exercise:'new exercise',weight:10,results:[{kind:'reps',reps:8}]}];
assert.equal(A.summarize(recentFixture,'recent')[0].exercise,'new exercise');
assert.equal(A.summarize(recentFixture)[0].exercise,'press');
const snapshot=A.exerciseSnapshot(sets,'press');
assert.equal(A.exerciseSnapshot(sets,'press',2026).sessionsThisYear,2);
assert.equal(A.exerciseSnapshot(sets,'press',2025).sessionsThisYear,0);
assert.equal(snapshot.sessions,2);assert.equal(snapshot.sets,3);assert.equal(snapshot.load,35);assert.equal(snapshot.lastDate,'2026-03-01');
assert.equal(A.exerciseSnapshot(sets,'missing').sessions,0);
assert.equal(A.exerciseSnapshot(sets,'Squat').exercise,'squats');
assert.equal(A.exerciseSnapshot(sets,'Explosive pull-up').exercise,'explosive pullups');
const actual=JSON.parse(fs.readFileSync(require('node:path').join(__dirname,'../../workouts/data/history.json'),'utf8')).workouts;
const parsed=A.records(actual);assert(parsed.sets.length>0);
assert(A.summarize(parsed.sets).every(row=>row.sets>=row.sessions));
const names=new Set(parsed.sets.map(set=>set.exercise));
for(const value of ['rows','bent over row','negatives','spotter arm bat hang','good form only baby','3 min rest','density','endurance','pullups']) assert(!names.has(value),value);
assert(names.has('explosive pullups'));
assert.equal(A.summarize(parsed.sets).find(row=>row.exercise==='weighted pullups').sessions,52);
console.log(`PASS: parsing, ambiguous values, archive edits, summary, calendar; imported ${actual.length} sessions / ${parsed.sets.length} interpreted rows / ${parsed.unparsed} other rows`);
