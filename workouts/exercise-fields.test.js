const assert=require('node:assert/strict');
const {setMeasurement,setLaterality}=require('./exercise-fields.js');
const {prepare,restore}=require('./session-archive.js');
const exercise={name:'hang',unilateral:false,measurement:'reps',fields:['Weight · lb','Reps'],values:[[25,6]],previous:[[20,5]]};
setMeasurement(exercise,'repeaters');
assert.deepEqual(exercise.fields,['Weight · lb','Reps','Duration · seconds']);
assert.deepEqual(exercise.values,[[25,6,'']]);
exercise.values[0][2]=7;
setLaterality(exercise,true);
assert.equal(exercise.fields.length,5);
exercise.values[0][3]=4;exercise.values[0][4]=8;
setLaterality(exercise,false);setLaterality(exercise,true);
assert.deepEqual(exercise.values,[[25,6,7,4,8]]);
setMeasurement(exercise,'duration');assert.deepEqual(exercise.values,[[25,7,8]]);
setMeasurement(exercise,'repeaters');assert.deepEqual(exercise.values,[[25,6,7,4,8]]);
const {entry,next}=prepare({date:'2026-11-12',notes:'',exercises:[exercise]},'2026-11-13','test');
assert.equal(entry.rows[0][2],'6 × 7s');assert.equal(entry.rows[0][3],'4 × 8s');
assert.deepEqual(restore(next,entry).exercises[0].values,[['25','6','7','4','8']]);
assert(next.exercises[0].values[0].every(v=>v===''));
const legacy={name:'hang',measurement:'repeaters',unilateral:false,fields:['Reps × seconds'],values:[['6 × 7s']],previous:[['5 x 8s']]};
setMeasurement(legacy,'repeaters');assert.deepEqual(legacy.values,[['6','7']]);assert.deepEqual(legacy.previous,[['5','8']]);
console.log('PASS: split repeater columns, weighted/unilateral combinations, modifier switching, legacy migration, archive round-trip');
